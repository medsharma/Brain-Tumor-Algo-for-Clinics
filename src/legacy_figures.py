# Figure 7 — Latent Space Projection (t-SNE)
# ══════════════════════════════════════════════════════════════════════════════

def plot_tsne(
    embeddings: np.ndarray,
    y_true: np.ndarray,
    uncertainties: np.ndarray,
    perplexity: float = 40,
    n_iter: int = 1_000,
) -> plt.Figure:
    """
    Reduces 768-D ViT embeddings to 2-D via t-SNE and plots two views:
      Left : colored by true class label.
      Right: colored by predictive entropy (continuous plasma colormap).

    Parameters
    ----------
    embeddings    : (N, 768) ViT CLS-token representations
    y_true        : (N,) true class indices
    uncertainties : (N,) predictive entropy values
    perplexity    : t-SNE perplexity  (recommended: 30–50)
    n_iter        : t-SNE iterations  (≥ 1000 for stability)
    """
    print(f"    Running t-SNE  (n={len(embeddings)}, perplexity={perplexity}) …")
    tsne   = TSNE(n_components=2, perplexity=perplexity, n_iter=n_iter,
                  init="pca", learning_rate="auto", random_state=42)
    emb2d  = tsne.fit_transform(embeddings)
    print(f"    t-SNE done.  KL divergence = {tsne.kl_divergence_:.4f}")

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.5), constrained_layout=True)
    dot_kw = dict(s=10, alpha=0.75, linewidths=0)

    # ── Left: True Class ──────────────────────────────────────────────────────
    ax = axes[0]
    for i, name in enumerate(CLASS_NAMES):
        mask = y_true == i
        ax.scatter(emb2d[mask, 0], emb2d[mask, 1],
                   color=_CB4[i], label=name, **dot_kw)
    ax.set_xlabel("t-SNE Dim 1")
    ax.set_ylabel("t-SNE Dim 2")
    ax.set_title("Latent Space — True Class")
    ax.legend(markerscale=2.2, fontsize=9.5)
    ax.set_xticks([]); ax.set_yticks([])
    _despine(ax)

    # ── Right: Predictive Entropy ─────────────────────────────────────────────
    ax = axes[1]
    sc = ax.scatter(emb2d[:, 0], emb2d[:, 1],
                    c=uncertainties, cmap="plasma", **dot_kw)
    cbar = fig.colorbar(sc, ax=ax, fraction=0.046, pad=0.04, shrink=0.92)
    cbar.set_label("Predictive Entropy  H[y|x]  (bits)", fontsize=10)
    cbar.ax.tick_params(labelsize=8)
    ax.set_xlabel("t-SNE Dim 1")
    ax.set_ylabel("t-SNE Dim 2")
    ax.set_title("Latent Space — Predictive Uncertainty")
    ax.set_xticks([]); ax.set_yticks([])
    _despine(ax)

    save_figure(fig, "fig7_tsne_latent_space")
    return fig



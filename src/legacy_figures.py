# Figure 2 — Enhanced Confusion Matrix
# ══════════════════════════════════════════════════════════════════════════════

def plot_confusion_matrix(y_true: np.ndarray, y_pred: np.ndarray) -> plt.Figure:
    """
    Confusion matrix annotated with raw counts AND row-normalized percentage.
    Single-hue Blues gradient; text color adapts to cell brightness.

    Parameters
    ----------
    y_true  : (N,) integer class indices
    y_pred  : (N,) integer class indices
    """
    cm      = confusion_matrix(y_true, y_pred)
    cm_norm = cm.astype(float) / cm.sum(axis=1, keepdims=True)

    fig, ax = plt.subplots(figsize=(6.5, 5.5))
    im = ax.imshow(cm_norm, cmap="Blues", vmin=0, vmax=1, aspect="auto")

    cbar = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    cbar.set_label("Proportion of True Class", fontsize=10)
    cbar.ax.tick_params(labelsize=8)

    # Annotate each cell
    threshold = 0.55   # switch text to white above this normalized value
    for r in range(N_CLASSES):
        for c in range(N_CLASSES):
            val    = cm_norm[r, c]
            color  = "white" if val > threshold else "black"
            weight = "bold"  if r == c else "normal"
            ax.text(c, r,
                    f"{cm[r, c]}\n({val*100:.1f}%)",
                    ha="center", va="center",
                    fontsize=9, color=color, fontweight=weight)

    ax.set_xticks(range(N_CLASSES))
    ax.set_yticks(range(N_CLASSES))
    ax.set_xticklabels(CLASS_NAMES, rotation=35, ha="right", fontsize=10)
    ax.set_yticklabels(CLASS_NAMES, fontsize=10)
    ax.set_xlabel("Predicted Label")
    ax.set_ylabel("True Label")
    ax.set_title("Confusion Matrix")
    # Keep all four spines for a matrix boundary
    for spine in ax.spines.values():
        spine.set_visible(True)

    fig.tight_layout()
    save_figure(fig, "fig2_confusion_matrix")
    return fig



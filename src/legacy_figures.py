# Synthetic Data Generator  (for standalone testing)
# ══════════════════════════════════════════════════════════════════════════════

def generate_synthetic_data(
    n_samples: int = 800,
    n_epochs:  int = 60,
    seed:      int = 42,
) -> dict:
    """
    Produces realistic-looking synthetic arrays matching all function signatures.

    Returns a dict with keys:
        history, best_epoch, y_true, y_pred, y_probs, uncertainties, embeddings
    """
    rng = np.random.default_rng(seed)
    t   = np.linspace(0, 1, n_epochs)

    # ── Training curves ───────────────────────────────────────────────────────
    train_loss = 1.45 * np.exp(-3.8 * t) + 0.05 + rng.normal(0, 0.012, n_epochs)
    val_loss   = 1.55 * np.exp(-3.2 * t) + 0.13 + rng.normal(0, 0.018, n_epochs)
    val_loss[40:] += np.linspace(0, 0.09, n_epochs - 40)   # mild overfitting
    train_acc  = np.clip(1 - 0.90 * np.exp(-4.2 * t) + rng.normal(0, 0.009, n_epochs), 0, 1)
    val_acc    = np.clip(1 - 0.88 * np.exp(-3.6 * t) + rng.normal(0, 0.011, n_epochs), 0, 1)
    best_epoch = int(np.argmin(val_loss)) + 1

    history = dict(train_loss=train_loss.tolist(), val_loss=val_loss.tolist(),
                   train_acc=train_acc.tolist(),   val_acc=val_acc.tolist())

    # ── Class-balanced ground truth ───────────────────────────────────────────
    y_true = np.repeat(np.arange(N_CLASSES), n_samples // N_CLASSES)
    y_true = np.concatenate([y_true, rng.integers(0, N_CLASSES, n_samples % N_CLASSES)])
    rng.shuffle(y_true)

    # ── Softmax probabilities  (~91% accuracy) ────────────────────────────────
    y_probs = rng.dirichlet(alpha=[0.4] * N_CLASSES, size=n_samples)
    boost   = rng.uniform(2.0, 5.0, size=n_samples)
    for i in range(n_samples):
        y_probs[i, y_true[i]] += boost[i]
    y_probs /= y_probs.sum(axis=1, keepdims=True)
    y_pred   = y_probs.argmax(axis=1)

    # ── Predictive entropy ────────────────────────────────────────────────────
    eps           = 1e-9
    uncertainties = -(y_probs * np.log(y_probs + eps)).sum(axis=1)

    # ── Simulated 768-D ViT embeddings ────────────────────────────────────────
    embeddings = np.zeros((n_samples, 768))
    for cls in range(N_CLASSES):
        idx   = np.where(y_true == cls)[0]
        mean  = rng.normal(cls * 6, 1.5, size=768)
        embeddings[idx] = rng.normal(mean, 1.8, size=(len(idx), 768))

    return dict(
        history=history, best_epoch=best_epoch,
        y_true=y_true, y_pred=y_pred, y_probs=y_probs,
        uncertainties=uncertainties, embeddings=embeddings,
    )



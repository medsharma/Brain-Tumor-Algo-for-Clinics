# Figure 6 — Accuracy–Rejection Curve (Clinical Deferral)
# ══════════════════════════════════════════════════════════════════════════════

def plot_accuracy_rejection_curve(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    uncertainties: np.ndarray,
    max_rejection: float = 0.50,
    n_steps: int = 100,
) -> plt.Figure:
    """
    Shows how model accuracy on retained samples rises as the top-X% most
    uncertain predictions are deferred to a human radiologist.

    Parameters
    ----------
    y_true         : (N,) true class indices
    y_pred         : (N,) predicted class indices
    uncertainties  : (N,) predictive entropy values
    max_rejection  : maximum fraction to defer  (default 0.50 → 50%)
    n_steps        : resolution of the X-axis grid
    """
    n              = len(y_true)
    baseline_acc   = (y_true == y_pred).mean()
    fracs          = np.linspace(0, max_rejection, n_steps)
    accs           = np.full(n_steps, np.nan)
    # Indices sorted highest → lowest uncertainty (most uncertain first)
    sorted_by_unc  = np.argsort(uncertainties)[::-1]

    for k, frac in enumerate(fracs):
        n_reject   = int(frac * n)
        keep_mask  = np.ones(n, dtype=bool)
        if n_reject > 0:
            keep_mask[sorted_by_unc[:n_reject]] = False
        if keep_mask.sum() > 0:
            accs[k] = (y_true[keep_mask] == y_pred[keep_mask]).mean()

    fig, ax = plt.subplots(figsize=(6.5, 4.5))
    ax.plot(fracs * 100, accs * 100,
            color=_CB4[0], linewidth=2.2, label="MC-Dropout model")
    ax.axhline(baseline_acc * 100, color="gray", linestyle="--", linewidth=1.2,
               label=f"No-rejection baseline  ({baseline_acc*100:.1f}%)")
    ax.fill_between(fracs * 100,
                    baseline_acc * 100,
                    np.where(np.isnan(accs), baseline_acc, accs) * 100,
                    where=(accs >= baseline_acc),
                    alpha=0.14, color=_CB4[0], label="Accuracy gain")

    ax.set_xlim(0, max_rejection * 100)
    ax.set_xlabel("Fraction of Samples Deferred to Radiologist  (%)")
    ax.set_ylabel("Accuracy on Retained Samples  (%)")
    ax.set_title("Accuracy–Rejection Curve  (Clinical Deferral)")
    ax.legend()
    _despine(ax)

    fig.tight_layout()
    save_figure(fig, "fig6_accuracy_rejection_curve")
    return fig



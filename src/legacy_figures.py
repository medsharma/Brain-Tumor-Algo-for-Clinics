# Figure 1 — Training Dynamics
# ══════════════════════════════════════════════════════════════════════════════

def plot_training_dynamics(history: dict, best_epoch: int | None = None) -> plt.Figure:
    """
    1×2 grid: Cross-Entropy Loss (left) and Accuracy (right).
    A vertical dotted line marks the epoch at which the best model was saved.

    Parameters
    ----------
    history     : dict with keys train_loss, val_loss, train_acc, val_acc
    best_epoch  : 1-indexed epoch of the best checkpoint (auto-detected from
                  minimum val_loss if None)
    """
    n_epochs = len(history["train_loss"])
    epochs   = np.arange(1, n_epochs + 1)

    if best_epoch is None:
        best_epoch = int(np.argmin(history["val_loss"])) + 1

    fig, axes = plt.subplots(1, 2, figsize=(10, 4), constrained_layout=True)

    # ── Loss ──────────────────────────────────────────────────────────────────
    ax = axes[0]
    ax.plot(epochs, history["train_loss"], color=_CB4[0], label="Train")
    ax.plot(epochs, history["val_loss"],   color=_CB4[1], linestyle="--", label="Validation")
    ax.axvline(best_epoch, color="gray", linestyle=":", linewidth=1.2,
               label=f"Best checkpoint (ep. {best_epoch})")
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Cross-Entropy Loss")
    ax.set_title("Training & Validation Loss")
    ax.legend()
    _despine(ax)

    # ── Accuracy ──────────────────────────────────────────────────────────────
    ax = axes[1]
    ax.plot(epochs, history["train_acc"], color=_CB4[0], label="Train")
    ax.plot(epochs, history["val_acc"],   color=_CB4[1], linestyle="--", label="Validation")
    ax.axvline(best_epoch, color="gray", linestyle=":", linewidth=1.2,
               label=f"Best checkpoint (ep. {best_epoch})")
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Accuracy")
    ax.set_ylim(0, 1.05)
    ax.set_title("Training & Validation Accuracy")
    ax.legend()
    _despine(ax)

    save_figure(fig, "fig1_training_dynamics")
    return fig



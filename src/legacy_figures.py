# Figure 5 — Model Calibration (Reliability Diagram)
# ══════════════════════════════════════════════════════════════════════════════

def plot_calibration_curve_fig(
    y_true: np.ndarray,
    y_probs: np.ndarray,
    n_bins: int = 10,
) -> plt.Figure:
    """
    Reliability diagram: predicted confidence vs. empirical accuracy.
    The dashed diagonal is the ideal perfectly-calibrated reference.
    Gap shading indicates over/under-confidence regions per class.

    Parameters
    ----------
    y_true  : (N,) true class indices
    y_probs : (N, 4) predicted probabilities
    n_bins  : number of equal-width bins for calibration_curve
    """
    y_bin = label_binarize(y_true, classes=list(range(N_CLASSES)))

    fig, ax = plt.subplots(figsize=(5.5, 5.5))
    ax.plot([0, 1], [0, 1], "k--", linewidth=1.2, label="Perfect calibration")

    for i, name in enumerate(CLASS_NAMES):
        frac_pos, mean_pred = calibration_curve(
            y_bin[:, i], y_probs[:, i],
            n_bins=n_bins, strategy="uniform",
        )
        ax.plot(mean_pred, frac_pos, "o-",
                color=_CB4[i], linewidth=1.6, markersize=5, label=name)
        ax.fill_between(mean_pred, mean_pred, frac_pos,
                        alpha=0.08, color=_CB4[i])

    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.set_xlabel("Mean Predicted Probability")
    ax.set_ylabel("Fraction of Positives  (Empirical Frequency)")
    ax.set_title("Reliability Diagram — Model Calibration")
    ax.legend(loc="upper left")
    _despine(ax)

    fig.tight_layout()
    save_figure(fig, "fig5_calibration_curve")
    return fig



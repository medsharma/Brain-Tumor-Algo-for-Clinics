def set_global_style() -> None:
    """Apply Nature-journal matplotlib rcParams globally."""
    # Prefer Arial; fall back gracefully on systems where it is absent.
    _font = "Arial" if "Arial" in matplotlib.font_manager.get_font_names() else "DejaVu Sans"
    matplotlib.rcParams.update({
        # Font
        "font.family":        _font,
        "font.size":          10,
        "axes.labelsize":     12,
        "axes.titlesize":     14,
        "axes.titleweight":   "bold",
        "axes.titlepad":      8,
        # Ticks
        "xtick.labelsize":    10,
        "ytick.labelsize":    10,
        "xtick.direction":    "out",
        "ytick.direction":    "out",
        "xtick.major.size":   3.5,
        "ytick.major.size":   3.5,
        # Spines (Tufte style — top/right removed per axis via _despine)
        "axes.spines.top":    False,
        "axes.spines.right":  False,
        "axes.linewidth":     0.8,
        # Legend
        "legend.fontsize":    9,
        "legend.frameon":     False,
        "legend.handlelength": 1.5,
        # Lines
        "lines.linewidth":    1.8,
        # Resolution
        "figure.dpi":         120,   # screen preview
        "savefig.dpi":        300,   # export
        # PDF text as editable paths (not bitmap/Type3)
        "pdf.fonttype":       42,
        "ps.fonttype":        42,
    })


def _despine(ax: plt.Axes) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


# ══════════════════════════════════════════════════════════════════════════════
# Save Helper
# ══════════════════════════════════════════════════════════════════════════════

def save_figure(fig: plt.Figure, stem: str) -> None:
    """Export *fig* as both PDF and PNG at 300 DPI into OUTPUT_DIR."""
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for fmt in ("pdf", "png"):
        path = os.path.join(OUTPUT_DIR, f"{stem}.{fmt}")
        fig.savefig(path, dpi=300, bbox_inches="tight", format=fmt)
        print(f"    Saved → {path}")



# Figure 3 — Multi-Class ROC & Precision–Recall Curves
# ══════════════════════════════════════════════════════════════════════════════

def plot_roc_pr_curves(y_true: np.ndarray, y_probs: np.ndarray) -> plt.Figure:
    """
    1×2 grid.
    Left : ROC curves for all 4 classes + macro + micro averages.
    Right: Precision–Recall curves for all 4 classes + micro average.
    AUC / AP values appear in legend labels (3 decimal places).

    Parameters
    ----------
    y_true  : (N,) integer class indices
    y_probs : (N, 4) predicted probability array
    """
    y_bin = label_binarize(y_true, classes=list(range(N_CLASSES)))
    fig, axes = plt.subplots(1, 2, figsize=(12, 5), constrained_layout=True)

    # ── ROC ───────────────────────────────────────────────────────────────────
    ax = axes[0]
    fpr_store, tpr_store = {}, {}
    for i, name in enumerate(CLASS_NAMES):
        fpr, tpr, _ = roc_curve(y_bin[:, i], y_probs[:, i])
        roc_auc = auc(fpr, tpr)
        fpr_store[i], tpr_store[i] = fpr, tpr
        ax.plot(fpr, tpr, color=_CB4[i], linewidth=1.8,
                label=f"{name}  (AUC = {roc_auc:.3f})")

    # Micro-average
    fpr_m, tpr_m, _ = roc_curve(y_bin.ravel(), y_probs.ravel())
    ax.plot(fpr_m, tpr_m, "k--", linewidth=1.4,
            label=f"Micro-avg  (AUC = {auc(fpr_m, tpr_m):.3f})")

    # Macro-average (interpolated)
    all_fpr   = np.unique(np.concatenate([fpr_store[i] for i in range(N_CLASSES)]))
    mean_tpr  = sum(np.interp(all_fpr, fpr_store[i], tpr_store[i])
                    for i in range(N_CLASSES)) / N_CLASSES
    ax.plot(all_fpr, mean_tpr, "k:", linewidth=1.4,
            label=f"Macro-avg  (AUC = {auc(all_fpr, mean_tpr):.3f})")

    ax.plot([0, 1], [0, 1], color="silver", linewidth=1.0)  # chance line
    ax.set_xlim(-0.01, 1.01)
    ax.set_ylim(-0.01, 1.05)
    ax.set_xlabel("False Positive Rate")
    ax.set_ylabel("True Positive Rate (Sensitivity)")
    ax.set_title("Receiver Operating Characteristic")
    ax.legend(loc="lower right", fontsize=8.5)
    _despine(ax)

    # ── Precision–Recall ──────────────────────────────────────────────────────
    ax = axes[1]
    for i, name in enumerate(CLASS_NAMES):
        prec, rec, _ = precision_recall_curve(y_bin[:, i], y_probs[:, i])
        ap = average_precision_score(y_bin[:, i], y_probs[:, i])
        ax.plot(rec, prec, color=_CB4[i], linewidth=1.8,
                label=f"{name}  (AP = {ap:.3f})")

    # Micro-average PR
    ap_micro  = average_precision_score(y_bin, y_probs, average="micro")
    prec_mi, rec_mi, _ = precision_recall_curve(y_bin.ravel(), y_probs.ravel())
    ax.plot(rec_mi, prec_mi, "k--", linewidth=1.4,
            label=f"Micro-avg  (AP = {ap_micro:.3f})")

    ax.set_xlim(-0.01, 1.01)
    ax.set_ylim(-0.01, 1.05)
    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    ax.set_title("Precision–Recall Curves")
    ax.legend(loc="upper right", fontsize=8.5)
    _despine(ax)

    save_figure(fig, "fig3_roc_pr_curves")
    return fig


# ══════════════════════════════════════════════════════════════════════════════
# Figure 4 — Uncertainty Reliability (Violin + Scatter)
# ══════════════════════════════════════════════════════════════════════════════

def plot_uncertainty_reliability(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    y_probs: np.ndarray,
    uncertainties: np.ndarray,
) -> plt.Figure:
    """
    1×2 grid.
    Left : Violin plot — predictive entropy for Correct vs. Misclassified.
    Right: Scatter — max confidence vs. entropy, colored by correctness.

    Parameters
    ----------
    y_true        : (N,) true class indices
    y_pred        : (N,) predicted class indices
    y_probs       : (N, 4) predicted probabilities
    uncertainties : (N,) predictive entropy values (bits)
    """
    correct  = y_true == y_pred
    max_conf = y_probs.max(axis=1)

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.8), constrained_layout=True)
    rng = np.random.default_rng(0)

    # ── Violin ────────────────────────────────────────────────────────────────
    ax = axes[0]
    groups  = [uncertainties[correct], uncertainties[~correct]]
    labels  = ["Correct", "Misclassified"]
    colors  = [_CB4[0], _RED]
    pos     = [1, 2]

    parts = ax.violinplot(groups, positions=pos,
                          showmedians=True, showextrema=True, widths=0.55)
    for i, body in enumerate(parts["bodies"]):
        body.set_facecolor(colors[i])
        body.set_alpha(0.65)
        body.set_edgecolor("none")

    for key in ("cmedians", "cbars", "cmins", "cmaxes"):
        parts[key].set_color("black")
        parts[key].set_linewidth(1.2)

    # Strip-plot overlay
    for i, (grp, p) in enumerate(zip(groups, pos)):
        jitter = rng.uniform(-0.09, 0.09, size=len(grp))
        ax.scatter(p + jitter, grp,
                   color=colors[i], alpha=0.22, s=7, zorder=3, linewidths=0)

    ax.set_xticks(pos)
    ax.set_xticklabels(labels)
    ax.set_ylabel("Predictive Entropy  H[y|x]  (bits)")
    ax.set_title("Uncertainty by Prediction Outcome")
    _despine(ax)

    # ── Scatter ───────────────────────────────────────────────────────────────
    ax = axes[1]
    ax.scatter(max_conf[correct],  uncertainties[correct],
               color=_CB4[0], alpha=0.40, s=14, linewidths=0, label="Correct")
    ax.scatter(max_conf[~correct], uncertainties[~correct],
               color=_RED,    alpha=0.65, s=14, linewidths=0, marker="X",
               label="Misclassified")
    ax.set_xlabel("Max Predicted Probability  (Confidence)")
    ax.set_ylabel("Predictive Entropy  (bits)")
    ax.set_title("Confidence vs. Uncertainty")
    ax.legend()
    _despine(ax)

    save_figure(fig, "fig4_uncertainty_reliability")
    return fig


